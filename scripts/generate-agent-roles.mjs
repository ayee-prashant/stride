import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { AGENT_ROLES, AGENT_ROLE_LABELS } from "../lib/agents.ts";

// The reviewed Markdown is the only editable prompt source. This generated module
// is bundled with Next.js so standalone deployment needs no filesystem fallbacks.
const names = ["BA", "SOLUTION_ARCHITECT", "DEVELOPER", "PEER_REVIEWER", "QA", "UAT", "RELEASE_OPERATIONS", "SECURITY_REVIEWER", "UX_ACCESSIBILITY", "PERFORMANCE_DATA", "DOCUMENTATION"];
const root = new URL("../docs/agent-workforce/templates/roles/", import.meta.url);
const base = readFileSync(new URL("BASE.md", root), "utf8");
const templates = AGENT_ROLES.map((role_id, i) => {
  const body = `${base}\n${readFileSync(new URL(`${names[i]}.md`, root), "utf8")}`;
  if (Buffer.byteLength(body) > 24_576) throw new Error("Role prompt exceeds its bounded template contract");
  return { role_id, label: AGENT_ROLE_LABELS[role_id], version: 1, hash: createHash("sha256").update(body).digest("hex"), body };
});
const output = "// Generated by scripts/generate-agent-roles.mjs. Edit the role Markdown, then regenerate.\nimport type { AgentTemplate } from '../agents.ts';\nexport const AGENT_TEMPLATES: AgentTemplate[] = " + JSON.stringify(templates, null, 2) + ";\n";
const target = new URL("../lib/server/agent-templates.generated.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== output) throw new Error("Role templates changed: run node scripts/generate-agent-roles.mjs and review the new hashes");
} else writeFileSync(target, output);
