import { createHash, randomBytes } from "node:crypto";
import { constants } from "node:fs";
import { lstat, mkdir, open, readFile, readdir, realpath } from "node:fs/promises";
import { createServer } from "node:net";
import { join } from "node:path";

const secret = () => randomBytes(32).toString("hex");
export function guardLocalEnvironment(environment, platform = process.platform, nodeVersion = process.versions.node) {
  if (platform === "win32") throw new Error("Use WSL with this local setup command; private Unix file permissions are required.");
  if (nodeVersion.split(".")[0] !== "24") throw new Error("Use Node 24, matching the repository and CI.");
  if (environment.NODE_ENV && environment.NODE_ENV !== "development") throw new Error("Local setup requires a development shell. It cannot run in test or production mode.");
  if (Object.entries(environment).some(([key, value]) => value && /^(DATABASE_|MIGRATION_|STRIDE_|BETTER_AUTH_|APP_URL$|RESEND_|RAILWAY_|VERCEL|AWS_|PG|PORT$)/.test(key))) throw new Error("Use a clean development shell without application, database, provider or production credentials.");
}
export function localDockerEndpoint(endpoint) {
  return typeof endpoint === "string" && endpoint.startsWith("unix:///") && !/[\r\n]/.test(endpoint);
}
export function validateSettings(value, root) {
  const expectedProject = `stride-local-${createHash("sha256").update(root).digest("hex").slice(0, 12)}`;
  if (!value || value.version !== 1 || value.root !== root || value.project !== expectedProject ||
      !Number.isInteger(value.appPort) || value.appPort < 1024 || value.appPort > 65535 ||
      !Number.isInteger(value.dbPort) || value.dbPort < 1024 || value.dbPort > 65535 || value.appPort === value.dbPort ||
      ![value.adminPassword, value.runtimePassword, value.authSecret, value.ownerPassword].every(v => typeof v === "string" && /^[a-f0-9]{64}$/.test(v))) {
    throw new Error("Local settings do not belong to this checkout or are invalid. Do not copy local settings between worktrees.");
  }
  return value;
}
export function runtimeText(settings) {
  return `# Generated by npm run setup:local. Development only.\nAPP_URL=http://127.0.0.1:${settings.appPort}\nDATABASE_URL=postgresql://stride_app:${settings.runtimePassword}@127.0.0.1:${settings.dbPort}/stride_local\nBETTER_AUTH_SECRET=${settings.authSecret}\nSTRIDE_ALLOWED_EMAILS=owner@stride.invalid\n`;
}
export function provisioningEnvironment(settings) {
  return { NODE_ENV: "development", MIGRATION_DATABASE_URL: `postgresql://stride_local:${settings.adminPassword}@127.0.0.1:${settings.dbPort}/stride_local`, STRIDE_RUNTIME_PASSWORD: settings.runtimePassword, STRIDE_ALLOWED_EMAILS: "owner@stride.invalid", STRIDE_BOOTSTRAP_EMAIL: "owner@stride.invalid", STRIDE_BOOTSTRAP_NAME: "Local owner", STRIDE_BOOTSTRAP_PASSWORD: settings.ownerPassword };
}
async function statOrNull(path) {
  try { return await lstat(path); } catch (error) { if (error.code === "ENOENT") return null; throw error; }
}
async function privateFile(path) {
  const stat = await statOrNull(path);
  if (!stat) return null;
  if (!stat.isFile() || stat.isSymbolicLink() || stat.uid !== process.getuid() || stat.nlink !== 1 || stat.mode & 0o077 || stat.size > 16384) throw new Error("Local configuration must be a small, private, owner-only regular file, never a link.");
  return readFile(path, "utf8");
}
async function createPrivate(path, text) {
  const file = await open(path, constants.O_WRONLY | constants.O_CREAT | constants.O_EXCL | constants.O_NOFOLLOW, 0o600);
  try { await file.writeFile(text); } finally { await file.close(); }
}
export async function verifyLocalRuntime(root, settings) {
  const names = await readdir(root);
  if (names.some(name => name.startsWith(".env") && ![".env.example", ".env.local"].includes(name))) throw new Error("An additional environment file could override local settings. Inspect it before using the managed local commands.");
  if (await privateFile(join(root, ".env.local")) !== runtimeText(settings)) throw new Error("Runtime configuration differs from managed local settings. It has not been changed.");
}
export async function availablePort(start, attempts = 1) {
  for (let port = start; port < start + attempts && port <= 65535; port++) {
    const available = await new Promise(resolve => {
      const server = createServer(); server.once("error", () => resolve(false));
      server.listen(port, "127.0.0.1", () => server.close(() => resolve(true)));
    });
    if (available) return port;
  }
  throw new Error("Requested local port is busy. Select unused --app-port and --db-port values in a new checkout.");
}
export async function loadLocalSettings(root) {
  root = await realpath(root);
  const directory = join(root, ".stride-local"); const stat = await statOrNull(directory);
  if (!stat) return null;
  if (!stat.isDirectory() || stat.isSymbolicLink() || stat.uid !== process.getuid() || stat.mode & 0o077) throw new Error("The local settings directory must be private (0700), owned by you, and not a symlink.");
  const contents = await privateFile(join(directory, "settings.json"));
  if (!contents) return null;
  try { return validateSettings(JSON.parse(contents), root); } catch { throw new Error("Invalid local settings. Preserve the files and use a separate checkout for a fresh setup."); }
}
export async function prepareLocalSettings(root, options = {}) {
  root = await realpath(root);
  for (const key of Object.keys(options)) if (!["appPort", "dbPort"].includes(key)) throw new Error("Unknown local setup option.");
  for (const value of Object.values(options)) if (!Number.isInteger(value) || value < 1024 || value > 65535) throw new Error("Ports must be integers between 1024 and 65535.");
  const names = await readdir(root);
  if (names.some(name => name.startsWith(".env") && ![".env.example", ".env.local"].includes(name))) throw new Error("Existing environment files are preserved. Use a separate checkout for managed local setup.");
  let settings = await loadLocalSettings(root);
  const existingRuntime = await privateFile(join(root, ".env.local"));
  if (!settings && existingRuntime !== null) throw new Error("Existing .env.local is preserved. Use a separate checkout for managed local setup.");
  if (settings && Object.entries(options).some(([key, value]) => settings[key] !== value)) throw new Error("Ports are already assigned to this checkout. Existing settings are preserved.");
  if (settings && existingRuntime !== null && existingRuntime !== runtimeText(settings)) throw new Error("Existing .env.local differs from managed settings. It has not been overwritten.");
  if (!settings) {
    const appPort = await availablePort(options.appPort ?? 3000, options.appPort ? 1 : 100);
    const dbPort = await availablePort(options.dbPort ?? 55432, options.dbPort ? 1 : 100);
    settings = validateSettings({ version: 1, root, project: `stride-local-${createHash("sha256").update(root).digest("hex").slice(0, 12)}`, appPort, dbPort, adminPassword: secret(), runtimePassword: secret(), authSecret: secret(), ownerPassword: secret() }, root);
    await mkdir(join(root, ".stride-local"), { recursive: true, mode: 0o700 });
    await createPrivate(join(root, ".stride-local/settings.json"), `${JSON.stringify(settings, null, 2)}\n`);
  }
  if (existingRuntime === null) await createPrivate(join(root, ".env.local"), runtimeText(settings));
  const loginPath = join(root, ".stride-local/LOGIN.txt");
  if (await privateFile(loginPath) === null) await createPrivate(loginPath, `Local development only\nURL: http://127.0.0.1:${settings.appPort}\nEmail: owner@stride.invalid\nInitial password: ${settings.ownerPassword}\n\nThis initial password is not reset on setup reruns. Keep any password you subsequently set in Stride.\n`);
  return settings;
}
